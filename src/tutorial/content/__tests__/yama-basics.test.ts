import { describe, expect, it } from 'vitest';
import type { GameEvent } from '../../../core/events/types';
import type {
  CheckpointStep,
  DemoStep,
  InfoStep,
  TutorialStep,
  WaitForEventStep,
  WorldHighlightTarget,
} from '../../types';
import { yamaBasicsTutorial } from '../yama-basics';

function makeHit(over: { targetId?: string; attackKind?: string; prayedCorrectly?: boolean | null } = {}): GameEvent {
  return {
    type: 'hit_applied',
    eventId: 1,
    tick: 1,
    targetId: over.targetId ?? 'player',
    damage: 0,
    blocked: true,
    attackKind: over.attackKind ?? 'magic_fire',
    prayedCorrectly: over.prayedCorrectly ?? null,
  } as GameEvent;
}

/**
 * Steps are generated by `buildGuidedDrill`, so the ladder's structural shape is locked in
 * guidedDrill.test.ts; these assertions cover the Basics-specific content.
 */
const steps = yamaBasicsTutorial.steps;

function stepByTitle(title: string): TutorialStep {
  const found = steps.find((s) => 'title' in s && s.title === title);
  if (!found) throw new Error(`No step titled "${title}"`);
  return found;
}

function stepAfter(title: string): TutorialStep {
  const idx = steps.findIndex((s) => 'title' in s && s.title === title);
  if (idx < 0) throw new Error(`No step titled "${title}"`);
  return steps[idx + 1];
}

describe('yamaBasicsTutorial — opening steps', () => {
  it('declares the max-mage equipment preset so the player starts in mage gear', () => {
    expect(yamaBasicsTutorial.encounterContext?.equipmentPresetKey).toBe('max-mage');
  });

  describe('Welcome to Yama P3', () => {
    const step = steps[0] as InfoStep;

    it('is the first step, info-kind, with no inline video', () => {
      expect(step.kind).toBe('info');
      expect(step.title).toBe('Welcome to Yama P3');
      expect(step.videoUrl).toBeUndefined();
    });

    it('mentions all four phase-3 mechanics', () => {
      expect(step.body).toContain('shadow waves');
      expect(step.body).toContain('fireballs');
      expect(step.body).toContain('void flares');
      expect(step.body).toContain('alternating magic/range');
    });
  });

  describe('Meet Yama', () => {
    const step = steps[1] as InfoStep;

    it('is an info step that highlights the Yama NPC', () => {
      expect(step.kind).toBe('info');
      expect(step.title).toBe('Meet Yama');
      expect(step.highlight).toBeDefined();
      const highlight = step.highlight as WorldHighlightTarget;
      expect(highlight.type).toBe('npc');
      if (highlight.type === 'npc') expect(highlight.actorId).toBe('yama');
    });

    it('mentions the mage-perspective framing and future melee techniques', () => {
      expect(step.body).toContain('mage perspective');
      expect(step.body).toContain('meleeing phase 3');
    });
  });
});

describe('yamaBasicsTutorial — prayer-swap drill (flagship)', () => {
  it('explains the attacks and teaches the northern-glyph tell', () => {
    const step = stepByTitle("Yama's Basic Attacks") as InfoStep;
    expect(step.kind).toBe('info');
    // Wiki: in P3 the first attack matches the more-abundant glyph color from earlier phases (the northern set here).
    expect(step.body).toContain('phase-3');
    expect(step.body.toLowerCase()).toContain('northern glyphs');
  });

  describe('the "Watch: Yama\'s Basic Attacks" demo', () => {
    const demo = stepByTitle("Watch: Yama's Basic Attacks") as DemoStep;

    it('is a demo step that resets + isolates attacks + forces magic-first', () => {
      expect(demo.kind).toBe('demo');
      // resetBefore must be false — the setup already owns the reset.
      expect(demo.resetBefore).toBe(false);
      const setMechanics = demo.setup?.find((a) => a.type === 'set-mechanics');
      expect(setMechanics?.type === 'set-mechanics' && setMechanics.mechanics.yamaMageRange).toBe(true);
      const opening = demo.setup?.find((action) => action.type === 'encounter-command');
      expect(opening?.type === 'encounter-command' && opening.commandId).toBe('yama-opening-magic');
    });

    it('fast-forwards to tick 5 (last setup action) and stops at offset 19', () => {
      // Cues stay absolute-tick anchored across the seek: 5 + 19 = engine tick 24.
      const ff = demo.setup?.find((a) => a.type === 'fast-forward-ticks');
      expect(ff?.type === 'fast-forward-ticks' && ff.toTick).toBe(5);
      const setup = demo.setup ?? [];
      expect(setup[setup.length - 1]?.type).toBe('fast-forward-ticks');
      expect(demo.stopAtTickOffset).toBe(19);
    });

    it('drives the swap via cursor cues: open prayer book, then Magic, then Missiles', () => {
      const targets = (demo.cursor?.cues ?? []).map((c) => c.target);
      expect(targets).toEqual([
        { kind: 'panel-tab', tab: 'prayer' },
        { kind: 'prayer', prayer: 'ProtectMagic' },
        { kind: 'prayer', prayer: 'ProtectRange' },
      ]);
    });

    it('clicks each cursor cue (so the real prayer handler runs)', () => {
      for (const cue of demo.cursor?.cues ?? []) {
        expect(cue.click ?? true).toBe(true);
      }
    });

    it('opens the book on a wall-clock cue but prays on ENGINE-TICK cues', () => {
      const times = (demo.cursor?.cues ?? []).map((c) => c.time);
      // Each prayer cue is one tick early so the prayer is active on Yama's attack: 10 -> 11, 17 -> 18.
      expect(times).toEqual([
        { kind: 'ms', ms: 900 },
        { kind: 'tick', tick: 10 },
        { kind: 'tick', tick: 17 },
      ]);
    });
  });

  describe('the "Your turn" ready beat', () => {
    const ready = stepByTitle('Your turn') as CheckpointStep;

    it('is a checkpoint that does NOT auto-advance (the explicit ready beat)', () => {
      expect(ready.kind).toBe('checkpoint');
      expect(ready.autoAdvance).toBe(false);
    });

    it('seeds attacks-only + magic-first so retry reproduces the prompt', () => {
      expect(ready.seed.mechanics?.yamaMageRange).toBe(true);
      expect(ready.seed.mechanics?.infiniteHealth).toBe(true);
      expect(ready.seed.encounterCommandIds).toEqual(['yama-opening-magic']);
    });
  });

  it('the practice requires 2 consecutive correctly-prayed Yama hits and resets the streak on a miss', () => {
    const practice = stepAfter('Your turn') as WaitForEventStep;
    expect(practice.kind).toBe('wait-for-event');
    expect(practice.eventName).toBe('hit_applied');
    expect(practice.count).toBe(2);
    expect(practice.failEventName).toBe('hit_applied');
    expect(practice.failResetsProgress).toBe(true);
    // Rides on the ready checkpoint's seed, so it must not re-reset.
    expect(practice.setup?.some((a) => a.type === 'reset')).toBeFalsy();

    expect(practice.matcher?.(makeHit({ prayedCorrectly: true, attackKind: 'magic_fire' }))).toBe(true);
    expect(practice.matcher?.(makeHit({ prayedCorrectly: true, attackKind: 'range_shadow' }))).toBe(true);
    expect(practice.matcher?.(makeHit({ prayedCorrectly: false, attackKind: 'magic_fire' }))).toBe(false);
    expect(practice.matcher?.(makeHit({ prayedCorrectly: true, targetId: 'yama' }))).toBe(false);

    expect(practice.failMatcher?.(makeHit({ prayedCorrectly: false, attackKind: 'range_shadow' }))).toBe(true);
    expect(practice.failMatcher?.(makeHit({ prayedCorrectly: true, attackKind: 'range_shadow' }))).toBe(false);
    expect(practice.failMatcher?.(makeHit({ prayedCorrectly: false, targetId: 'yama' }))).toBe(false);
  });
});

describe('yamaBasicsTutorial — every practice section has a ready beat', () => {
  const readyBeatTitles = ['Your turn', 'Ready?'];

  it('precedes each wait-for-event practice with a non-auto-advancing checkpoint', () => {
    const practices = steps.filter((s) => s.kind === 'wait-for-event');
    expect(practices.length).toBe(4);

    for (const practice of practices) {
      const idx = steps.indexOf(practice);
      const prev = steps[idx - 1];
      expect(prev.kind).toBe('checkpoint');
      expect((prev as CheckpointStep).autoAdvance).toBe(false);
      expect(readyBeatTitles).toContain((prev as CheckpointStep).title);
    }
  });
});

describe('yamaBasicsTutorial — hand-tuned practice configs preserved', () => {
  it('keeps the waves ramp (wait-ticks 30) and count', () => {
    const practice = stepByTitle('Survive the waves') as WaitForEventStep;
    expect(practice.eventName).toBe('wave_activated');
    expect(practice.count).toBe(18);
    const waitTicks = practice.setup?.find((a) => a.type === 'wait-ticks');
    expect(waitTicks?.type === 'wait-ticks' && waitTicks.ticks).toBe(30);
    expect(practice.setup?.some((a) => a.type === 'reset')).toBeFalsy();
  });

  it('keeps the fireballs count', () => {
    const practice = stepByTitle('Dodge the fireballs') as WaitForEventStep;
    expect(practice.eventName).toBe('fireball_impact');
    expect(practice.count).toBe(3);
  });

  it('keeps the flares fail-event and spawns 2 flares without re-resetting', () => {
    const practice = stepByTitle('Kill 2 flares before they explode') as WaitForEventStep;
    expect(practice.eventName).toBe('voidflare_destroyed');
    expect(practice.count).toBe(2);
    expect(practice.failEventName).toBe('voidflare_exploded');
    const spawns = practice.setup?.filter(
      (action) => action.type === 'encounter-command' && action.commandId === 'yama-spawn-void-flare',
    );
    expect(spawns?.length).toBe(2);
    expect(practice.setup?.some((a) => a.type === 'reset')).toBeFalsy();
  });
});

describe('yamaBasicsTutorial — mechanically accurate drill copy', () => {
  function drillCopy(explainTitle: string, readyTitle: string, practiceTitle: string): string {
    return [stepByTitle(explainTitle), stepByTitle(readyTitle), stepByTitle(practiceTitle)]
      .map((step) => ('body' in step ? step.body : ''))
      .join(' ');
  }

  describe('fireballs', () => {
    const copy = () => drillCopy('Fireballs', 'Ready?', 'Dodge the fireballs');

    it('never claims the floor telegraphs the impact', () => {
      // Fireball danger tiles render at impact, not before.
      expect(copy()).not.toMatch(/light up|lit tiles|marked tiles/i);
    });

    it('describes the hourglass detonation and the sideways dodge', () => {
      const text = copy();
      expect(text).toMatch(/hourglass/i);
      // getFireballPerfectDodgeTiles returns exactly the two tiles beside the middle fireball.
      expect(text).toMatch(/to the side/i);
      expect(text).toMatch(/middle/i);
    });
  });

  describe('void flares', () => {
    const explain = () => (stepByTitle('Void Flares') as InfoStep).body;

    it('does not claim the killing blow can roll low', () => {
      // Wiki (Void Flare): players are guaranteed a maximum hit with magic or standard ranged.
      expect(explain()).not.toMatch(/not guaranteed|rolls accuracy/i);
    });

    it('states that magic and standard ranged always deal max damage', () => {
      const text = explain();
      expect(text).toMatch(/max damage/i);
      // The number that actually matters: a P3 flare spawns on 71 HP.
      expect(text).toMatch(/71/);
    });
  });
});

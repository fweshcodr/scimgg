/**
 * Facts extracted from a private gameplay capture (colosseum-waves-1-12-damage-trials-solarflare3-volatility3-bees1-totemic-doom1-death-packet-data.txt).
 * Run A's healing totems and what they touched. An NPC life runs from its `add` to its `del`
 * (indices are reused). `fills` are `[tick, headbar id=0 fill]` and `spotanims` the default-slot
 * spotanim names on each tick a heal splat landed on the life. A totem's `target` is the life its
 * add tick's `facing npc=` names, else its first projectile's target; `launches` are its attack-sequence ticks and `hits` the player's
 * `[tick, "splat id:value"]` on it. `projectiles` are its projectile records (`totem` and
 * `target` are NPC indices), `heals` every heal splat (id 6) on an NPC, and `npcTypes` each
 * index's last NPC type with a known max HP.
 */
export interface CapturedLife {
  readonly index: number;
  readonly add: number;
  readonly del: number | null;
  readonly fills: readonly (readonly [tick: number, fill: number])[];
  readonly spotanims: readonly (readonly [tick: number, names: readonly string[]])[];
}

export interface CapturedTotem {
  readonly index: number;
  readonly add: number;
  readonly life: number;
  readonly target: number | null;
  readonly launches: readonly number[];
  readonly hits: readonly (readonly [tick: number, splat: string])[];
}

export interface CapturedTotemProjectile {
  readonly tick: number;
  readonly totem: number;
  readonly target: number;
  readonly fields: {
    readonly startTime: number;
    readonly endTime: number;
    readonly angle: number;
    readonly progress: number;
    readonly startHeight: number;
    readonly endHeight: number;
  };
}

